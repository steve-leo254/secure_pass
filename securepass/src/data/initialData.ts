const now = new Date();
const today = (hours: number, mins: number) => {
  const d = new Date(now);
  d.setHours(hours, mins, 0, 0);
  return d.toISOString();
};
const yesterday = (hours: number, mins: number) => {
  const d = new Date(now);
  d.setDate(d.getDate() - 1);
  d.setHours(hours, mins, 0, 0);
  return d.toISOString();
};

